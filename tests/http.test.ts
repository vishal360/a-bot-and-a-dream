import { test, expect } from 'bun:test';
import { defaultConfig } from '../src/domain';
test('HTTP boundary, backtest, promotion and durable halt workflow', async () => {
  // Isolated working directory keeps integration state away from operator data.
  const { mkdtempSync, rmSync } = await import('node:fs');
  const { tmpdir } = await import('node:os'); const { join, resolve } = await import('node:path');
  const dir = mkdtempSync(join(tmpdir(), 'dream-http-'));
  const port = 18000 + Math.floor(Math.random() * 10000), base = `http://127.0.0.1:${port}`;
  const proc = Bun.spawn([process.execPath, resolve('src/server.ts')], { cwd: dir, env: { ...process.env, PORT: String(port) }, stdout: 'ignore', stderr: 'pipe' });
  const post = (path: string, body: unknown, origin = base) => fetch(base + '/api/' + path, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin }, body: JSON.stringify(body) });
  try {
    let ready = false;
    for (let i = 0; i < 100; i++) { try { ready = (await fetch(base + '/api/health')).ok; } catch {} if (ready) break; await Bun.sleep(50); }
    expect(ready).toBe(true);
    expect((await (await fetch(base + '/api/health')).json()).liveTrading).toBe(false);
    const simulation = await (await fetch(base + '/api/paper/session')).json();
    expect(simulation.account).toBe('paper-mainnet'); expect(simulation.capital).toBe(10000); expect(simulation.enabled).toBe(false);
    expect((await post('paper/session', { enabled: true }, 'https://attacker.example')).status).toBe(403);
    expect((await post('paper/session', { enabled: 'true' })).status).toBe(400);
    expect((await post('paper/mainnet-order', { side: 'buy', quantity: .001 })).status).toBe(400);
    const readiness = await (await fetch(base + '/api/readiness')).json();
    expect(readiness.readyThroughStep4).toBe(false); expect(readiness.agentsEnabled).toBe(false);
    expect(readiness.gates).toHaveLength(3);
    expect((await (await fetch(base + '/api/risk/execution')).json()).reconciliation).toBe('required');
    expect((await post('risk/execution', { equity: 1000000 })).status).toBe(404);
    expect((await post('halt', {}, 'https://attacker.example')).status).toBe(403);
    expect((await post('command', { id: 'atlas', action: 'start' })).status).toBe(400);
    expect((await post('paper/order', { botId: 'atlas', side: 'buy', quantity: 1 })).status).toBe(400);
    expect((await fetch(base + '/api/markets')).status).toBe(200);
    expect((await (await fetch(base + '/api/risk/allocation')).json()).allocationPct).toBe(0);
    expect((await (await fetch(base + '/api/risk/allocation/preview')).json()).equity).toBeNull();
    expect((await post('risk/allocation', { allocationPct: 75 }, 'https://attacker.example')).status).toBe(403);
    expect((await post('risk/allocation', { allocationPct: 101 })).status).toBe(400);
    expect((await (await post('risk/allocation', { allocationPct: 75 })).json()).allocationPct).toBe(75);
    expect((await (await fetch(base + '/api/lighter')).json()).config).toBeNull();
    expect((await post('halt', {})).status).toBe(200);
    expect((await post('command', { id: 'atlas', action: 'start' })).status).toBe(400);
    expect((await post('reset', { confirm: 'wrong' })).status).toBe(400);
    expect((await post('reset', { confirm: 'RESET' })).status).toBe(200);
    const run = await (await post('backtest', { config: { ...defaultConfig, asset: 'crypto' } })).json();
    expect(run.result.source).toBe('synthetic'); expect((await post('promote', { id: run.id })).status).toBe(200);
    const state = await (await fetch(base + '/api/state')).json(); expect(state.strategies.length).toBe(1); expect(state.bots.every((b: any) => b.status === 'paused')).toBe(true);
    expect((await post('backtest', { config: { ...defaultConfig, riskPct: .5 } })).status).toBe(400);
    const { token } = await (await post('ingestion-token', {})).json();
    const ingest = (path: string, body: unknown, key = token) => fetch(base + '/api/ingest/' + path, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${key}` }, body: JSON.stringify(body) });
    const fill = { id: 'external-1', account: 'ibkr-paper', botId: 'atlas', symbol: 'MES-202612', side: 'buy', quantity: 1, price: 5000, fee: 1, multiplier: 5, time: '2026-01-01T00:00:00.000Z', reason: 'test' };
    expect((await ingest('fill', fill, 'wrong')).status).toBe(401);
    expect((await (await ingest('fill', fill)).json()).inserted).toBe(true);
    expect((await (await ingest('fill', fill)).json()).inserted).toBe(false);
    expect((await ingest('mark', { account: 'paper', symbol: 'MES', price: 1, time: new Date().toISOString() })).status).toBe(400);
    expect((await ingest('mark', { account: 'ibkr-paper', symbol: 'MES-202612', price: 5010, time: new Date().toISOString() })).status).toBe(200);
    expect((await ingest('heartbeat', { botId: 'atlas', message: 'ready' })).status).toBe(200);
    const ops = await (await fetch(base + '/api/operations')).json();
    expect(ops.accounts.find((a: any) => a.account === 'ibkr-paper').analytics.unrealized).toBe(50);
    expect(JSON.stringify(ops)).not.toContain(token);
    expect((await post('fills/import', { fills: [{ ...fill, id: 'rollback-1' }, { ...fill, id: 'rollback-2', price: -1 }] })).status).toBe(400);
    const after = await (await fetch(base + '/api/operations')).json(); expect(after.fills).toHaveLength(1);
    expect((await post('stats/reset', { confirm: 'wrong' })).status).toBe(400);
    expect((await post('stats/reset', { confirm: 'ARCHIVE AND RESET' })).status).toBe(400);
    expect((await (await ingest('fill', { ...fill, id: 'external-close', side: 'sell', price: 5010 })).json()).inserted).toBe(true);
    const archive = await (await post('stats/reset', { confirm: 'ARCHIVE AND RESET' })).json();
    expect(archive.id).toBeString();
    expect((await (await fetch(base + '/api/stats/archives')).json()).length).toBe(1);
    expect((await (await fetch(base + '/api/stats/archive?id=' + archive.id)).json()).fills).toHaveLength(2);
    expect((await (await fetch(base + '/api/operations')).json()).fills).toHaveLength(0);
    expect((await (await fetch(base + '/api/risk/allocation')).json()).allocationPct).toBe(75);
  } finally { proc.kill(); await proc.exited; rmSync(dir, { recursive: true, force: true }); }
}, 20000);